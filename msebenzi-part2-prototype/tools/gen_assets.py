def logo_png(size, shape):
    """Legacy (pre-API 26) launcher icon at `size` px. shape: square|round|full"""
    bg = logo_background().to_image(scale=max(1, math.ceil(size / 108 * 2)))
    fg = logo_foreground().to_image(scale=max(1, math.ceil(size / 108 * 2)))
    img = Image.alpha_composite(bg, fg).resize((size, size), Image.LANCZOS)
    if shape == "full":
        return img
    mask = Image.new("L", (size * 4, size * 4), 0)
    d = ImageDraw.Draw(mask)
    if shape == "round":
        d.ellipse([0, 0, size * 4 - 1, size * 4 - 1], fill=255)
    else:
        d.rounded_rectangle([0, 0, size * 4 - 1, size * 4 - 1], radius=int(size * 4 * 0.22), fill=255)
    mask = mask.resize((size, size), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.paste(img, (0, 0), mask)
    return out


