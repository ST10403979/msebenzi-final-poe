# ---------------------------------------------------------------- primitives
class Scene:
    def __init__(self, w=W, h=H):
        self.w, self.h, self.items = w, h, []

    def rect(self, x, y, w, h, c, a=1.0):
        self.items.append(("poly", [(x, y), (x + w, y), (x + w, y + h), (x, y + h)], c, a))

    def rrect(self, x, y, w, h, r, c, a=1.0):
        self.items.append(("rrect", (x, y, w, h, r), c, a))

    def circle(self, cx, cy, r, c, a=1.0):
        self.items.append(("circle", (cx, cy, r), c, a))

    def poly(self, pts, c, a=1.0):
        self.items.append(("poly", pts, c, a))

    def ellipse(self, cx, cy, rx, ry, rot, c, a=1.0):
        pts = []
        cr, sr = math.cos(math.radians(rot)), math.sin(math.radians(rot))
        for i in range(28):
            t = 2 * math.pi * i / 28
            x, y = rx * math.cos(t), ry * math.sin(t)
            pts.append((cx + x * cr - y * sr, cy + x * sr + y * cr))
        self.items.append(("poly", pts, c, a))

    def multi(self, parts, c, a=1.0):
        """Single even-odd path: first part is the outline, the rest are holes (must not overlap each other)."""
        self.items.append(("multi", parts, c, a))

    def line(self, x1, y1, x2, y2, wd, c, a=1.0):
        dx, dy = x2 - x1, y2 - y1
        d = math.hypot(dx, dy) or 1
        nx, ny = -dy / d * wd / 2, dx / d * wd / 2
        self.poly([(x1 + nx, y1 + ny), (x2 + nx, y2 + ny), (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)], c, a)

    def star(self, cx, cy, r, c, a=1.0):
        k = r * 0.28
        self.poly([(cx, cy - r), (cx + k, cy - k), (cx + r, cy), (cx + k, cy + k),
                   (cx, cy + r), (cx - k, cy + k), (cx - r, cy), (cx - k, cy - k)], c, a)

    # ---- exporters
    def to_vector_xml(self, dp_w=None, dp_h=None):
        f = lambda v: ("%.2f" % v).rstrip("0").rstrip(".")
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               '<!-- Generated by tools/gen_assets.py - original artwork. -->',
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
               '    android:width="%sdp"' % f(dp_w or self.w),
               '    android:height="%sdp"' % f(dp_h or self.h),
               '    android:viewportWidth="%s"' % f(self.w),
               '    android:viewportHeight="%s">' % f(self.h)]
        for kind, g, c, a in self.items:
            if kind == "multi":
                subs = []
                for pk, pg in g:
                    if pk == "poly":
                        subs.append("M" + " L".join("%s,%s" % (f(x), f(y)) for x, y in pg) + " Z")
                    else:
                        cx, cy, r = pg
                        subs.append("M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0 Z" % (f(cx - r), f(cy), f(r), f(r), f(2 * r), f(r), f(r), f(-2 * r)))
                alpha = '' if a >= 1 else '\n        android:fillAlpha="%s"' % f(a)
                out.append('    <path\n        android:fillColor="%s"\n        android:fillType="evenOdd"%s\n        android:pathData="%s" />' % (c, alpha, " ".join(subs)))
                continue
            if kind == "poly":
                d = "M" + " L".join("%s,%s" % (f(x), f(y)) for x, y in g) + " Z"
            elif kind == "circle":
                cx, cy, r = g
                d = "M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0 Z" % (f(cx - r), f(cy), f(r), f(r), f(2 * r), f(r), f(r), f(-2 * r))
            else:
                x, y, w, h, r = g
                d = ("M%s,%s H%s A%s,%s 0 0 1 %s,%s V%s A%s,%s 0 0 1 %s,%s H%s A%s,%s 0 0 1 %s,%s V%s A%s,%s 0 0 1 %s,%s Z" % (
                    f(x + r), f(y), f(x + w - r), f(r), f(r), f(x + w), f(y + r), f(y + h - r), f(r), f(r), f(x + w - r), f(y + h),
                    f(x + r), f(r), f(r), f(x), f(y + h - r), f(y + r), f(r), f(r), f(x + r), f(y)))
            alpha = '' if a >= 1 else '\n        android:fillAlpha="%s"' % f(a)
            out.append('    <path\n        android:fillColor="%s"%s\n        android:pathData="%s" />' % (c, alpha, d))
        out.append('</vector>')
        return "\n".join(out) + "\n"

    def to_image(self, scale=4):
        S = scale
        img = Image.new("RGBA", (self.w * S, self.h * S), (0, 0, 0, 0))
        for kind, g, c, a in self.items:
            layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
            d = ImageDraw.Draw(layer)
            rgb = tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))
            col = rgb + (int(255 * a),)
            if kind == "multi":
                for i, (pk, pg) in enumerate(g):
                    fillc = col if i == 0 else (0, 0, 0, 0)
                    tmp = Image.new("RGBA", img.size, (0, 0, 0, 0)); td = ImageDraw.Draw(tmp)
                    if pk == "poly":
                        td.polygon([(x * S, y * S) for x, y in pg], fill=col)
                    else:
                        cx, cy, r = pg
                        td.ellipse([(cx - r) * S, (cy - r) * S, (cx + r) * S, (cy + r) * S], fill=col)
                    if i == 0:
                        layer = Image.alpha_composite(layer, tmp)
                    else:
                        px = layer.load(); tp = tmp.load()
                        for yy in range(layer.size[1]):
                            for xx in range(layer.size[0]):
                                if tp[xx, yy][3] > 0: px[xx, yy] = (0, 0, 0, 0)
                img = Image.alpha_composite(img, layer)
                continue
            if kind == "poly":
                d.polygon([(x * S, y * S) for x, y in g], fill=col)
            elif kind == "circle":
                cx, cy, r = g
                d.ellipse([(cx - r) * S, (cy - r) * S, (cx + r) * S, (cy + r) * S], fill=col)
            else:
                x, y, w, h, r = g
                d.rounded_rectangle([x * S, y * S, (x + w) * S, (y + h) * S], radius=r * S, fill=col)
            img = Image.alpha_composite(img, layer)
        return img


